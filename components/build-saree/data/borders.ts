function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

function buildBorders(): CatalogItem[] {
  const seen = new Set<string>();
  const out: CatalogItem[] = [];

  for (const seed of SEEDS) {
    seed.names.forEach((name, i) => {
      let id = slugify(name);
      if (seen.has(id)) id = `${id}-${seed.category.toLowerCase()}`;
      if (seen.has(id)) id = `${id}-${i + 1}`;
      seen.add(id);

      const priceJitter = ((i % 5) - 2) * 150;
      out.push({
        id,
        name,
        type: 'border',
        description: seed.tones[i % seed.tones.length],
        tone: seed.category,
        priceAdjustment: Math.max(900, seed.basePrice + priceJitter),
        texture: seed.texture,
        mask: 'border-mask',
      });
    });
  }

  // Pad to 320+ with numbered variants across families for deep catalogue depth
  let n = 1;
  while (out.length < 320) {
    const seed = SEEDS[n % SEEDS.length];
    const base = seed.names[n % seed.names.length];
    const id = `${slugify(base)}-var-${n}`;
    if (!seen.has(id)) {
      seen.add(id);
      out.push({
        id,
        name: `${base} ${String(n).padStart(3, '0')}`,
        type: 'border',
        description: seed.tones[n % seed.tones.length],
        tone: seed.category,
        priceAdjustment: Math.max(900, seed.basePrice + (n % 7) * 100),
        texture: seed.texture,
        mask: 'border-mask',
      });
    }
    n += 1;
    if (n > 500) break;
  }

  return out;
}

/** 320+ saree border designs across heritage + contemporary families */
export const BORDERS: CatalogItem[] = buildBorders();

export function borderTextureOf(borderId: string): BorderTexture {
  const found = BORDERS.find((b) => b.id === borderId);
  return (found?.texture as BorderTexture) ?? 'classic';
}

export function bordersInCategory(category: BorderCategory): CatalogItem[] {
  if (category === 'All') return BORDERS;
  return BORDERS.filter((b) => b.tone === category);
}
